import type { ClassInfo } from '@/data/books';
import type { ClassDetailContent } from '@/lib/classDetails';

function classLabel(cls: ClassInfo) {
  return cls.nameTa;
}

function getStageName(classId: number) {
  if (classId <= 5) return 'தொடக்கப்பள்ளி';
  if (classId <= 7) return 'இடைநிலைப்பள்ளி';
  if (classId <= 10) return 'மேல்நிலைப்பள்ளி அடித்தளம்';
  return 'உயர்நிலைப் பள்ளி மற்றும் பொதுத்தேர்வு தயாரிப்பு';
}

