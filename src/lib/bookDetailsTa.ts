function findInternalLinksTa(cls: ClassInfo, book: Book) {
  return cls.books
    .filter((candidate) => candidate.id !== book.id && candidate.medium === book.medium)
    .slice(0, 2)
    .map((candidate) => ({
      label: `${cls.nameTa} ${candidate.subjectTa} விவரங்கள்`,
      href: `/class/${cls.id}/book/${candidate.id}`,
    }));
}

